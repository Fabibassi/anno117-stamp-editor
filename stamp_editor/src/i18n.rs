//! Editor UI language (DE/EN). Game catalog names come from Anno texts separately.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    De,
    #[default]
    En,
}

impl Language {
    pub const ALL: [Language; 2] = [Language::De, Language::En];

    pub fn from_config(s: &str) -> Self {
        match s.trim().to_ascii_lowercase().as_str() {
            "de" | "deutsch" | "german" => Language::De,
            _ => Language::En,
        }
    }

    pub fn as_config(self) -> &'static str {
        match self {
            Language::De => "de",
            Language::En => "en",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Language::De => "Deutsch",
            Language::En => "English",
        }
    }
}

/// Translate an editor chrome key. Missing keys fall back to German, then `"???"`.
pub fn tr(lang: Language, key: &str) -> &'static str {
    lookup(lang, key)
        .or_else(|| lookup(Language::De, key))
        .unwrap_or("???")
}

pub fn tr_fmt(lang: Language, key: &str, args: &[(&str, &str)]) -> String {
    let mut s = tr(lang, key).to_string();
    for (k, v) in args {
        s = s.replace(&format!("{{{k}}}"), v);
    }
    s
}

fn lookup(lang: Language, key: &str) -> Option<&'static str> {
    let table = match lang {
        Language::De => DE,
        Language::En => EN,
    };
    table.iter().find(|(k, _)| *k == key).map(|(_, v)| *v)
}

macro_rules! entries {
    ($(($k:literal, $v:literal)),* $(,)?) => {
        &[$(($k, $v)),*]
    };
}

